package com.trustgate.core.db;

import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.List;
import javax.sql.DataSource;

/**
 * Tables are written for Oracle (VARCHAR2, NUMBER, identity columns from 12c) and also run on
 * H2 in Oracle compatibility mode for tests and the quick-start profile.
 */
public final class Schema {
    private static final List<String> DDL = List.of(
            """
            CREATE TABLE TG_KEYS (
              VERSION      NUMBER(10)    NOT NULL,
              PURPOSE      VARCHAR2(10)  NOT NULL,
              WRAPPED_KEY  VARCHAR2(200) NOT NULL,
              STATUS       VARCHAR2(10)  NOT NULL,
              CREATED_AT   TIMESTAMP     NOT NULL,
              CONSTRAINT PK_TG_KEYS PRIMARY KEY (VERSION, PURPOSE)
            )""",
            """
            CREATE TABLE TG_USERS (
              ID             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              USERNAME       VARCHAR2(50)  NOT NULL,
              PASSWORD_HASH  VARCHAR2(200) NOT NULL,
              DISPLAY_NAME   VARCHAR2(100) NOT NULL,
              USER_ROLE      VARCHAR2(10)  NOT NULL,
              EMAIL          VARCHAR2(200),
              RRN_ENC        VARCHAR2(400),
              RRN_IDX        VARCHAR2(64),
              PHONE_ENC      VARCHAR2(400),
              PHONE_IDX      VARCHAR2(64),
              OTP_SECRET_ENC VARCHAR2(400),
              OTP_ENABLED    NUMBER(1)  DEFAULT 0 NOT NULL,
              OTP_LAST_STEP  NUMBER(19),
              FAILED_COUNT   NUMBER(5)  DEFAULT 0 NOT NULL,
              LOCKED_UNTIL   TIMESTAMP,
              CREATED_AT     TIMESTAMP  NOT NULL,
              CONSTRAINT UQ_TG_USERS_NAME UNIQUE (USERNAME)
            )""",
            "CREATE INDEX IX_TG_USERS_RRN ON TG_USERS (RRN_IDX)",
            "CREATE INDEX IX_TG_USERS_PHONE ON TG_USERS (PHONE_IDX)",
            """
            CREATE TABLE TG_AUDIT (
              ID          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              TS          TIMESTAMP    NOT NULL,
              USERNAME    VARCHAR2(50),
              EVENT_TYPE  VARCHAR2(40) NOT NULL,
              DETAIL      VARCHAR2(400),
              CLIENT_IP   VARCHAR2(45)
            )""",
            "CREATE INDEX IX_TG_AUDIT_TS ON TG_AUDIT (TS)");

    private Schema() {}

    /** Creates the tables if they do not exist yet. Returns true when it created them. */
    public static boolean ensure(DataSource ds) throws SQLException {
        try (Connection c = ds.getConnection()) {
            try (Statement s = c.createStatement()) {
                s.executeQuery("SELECT COUNT(*) FROM TG_USERS").close();
                return false;
            } catch (SQLException missing) {
                // fall through and create
            }
            try (Statement s = c.createStatement()) {
                for (String ddl : DDL) s.execute(ddl);
            }
            if (!c.getAutoCommit()) c.commit();
            return true;
        }
    }
}
