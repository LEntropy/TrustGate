SET LINESIZE 220
SET PAGESIZE 100
SET FEEDBACK OFF
COLUMN USERNAME FORMAT A10
COLUMN RRN_ENC FORMAT A62
COLUMN RRN_IDX FORMAT A20
COLUMN OTP_SECRET_ENC FORMAT A30
COLUMN PURPOSE FORMAT A7
COLUMN STATUS FORMAT A8
COLUMN WRAPPED_KEY FORMAT A60

PROMPT
PROMPT ===== TG_USERS: what is actually stored for each user =====
SELECT USERNAME, RRN_ENC, SUBSTR(RRN_IDX, 1, 20) AS RRN_IDX,
       SUBSTR(OTP_SECRET_ENC, 1, 30) AS OTP_SECRET_ENC
  FROM TG_USERS ORDER BY ID;

PROMPT
PROMPT ===== TG_KEYS: data keys, stored wrapped by the KEK =====
SELECT VERSION, PURPOSE, STATUS, SUBSTR(WRAPPED_KEY, 1, 60) AS WRAPPED_KEY
  FROM TG_KEYS ORDER BY PURPOSE, VERSION;
EXIT
